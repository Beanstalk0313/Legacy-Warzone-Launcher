/**
 * Translation helper function
 * Usage: t('tab.play', lang) or t('join.title.join', lang, { server: 'My Server' })
 */
export function t(key, lang = 'en', params = null) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en
  let str = dict[key] || TRANSLATIONS.en[key] || key
  if (params && typeof str === 'string') {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\{${k}\}`, 'g'), String(v))
    }
  }
  return str
}

/**
 * React hook for accessing current language and translation function
 */
export function useTranslation() {
  const { settings } = useSettings()
  const lang = settings?.language || 'en'
  return {
    t: (key, params) => t(key, lang, params),
    lang,
  }
}
